def analyse(name, rows):
    c = np.array([r[0] for r in rows]); v = np.array([r[1] for r in rows])
    r = np.diff(np.log(c)); lv = np.log(v)
    corr = np.corrcoef(lv[1:], np.abs(r))[0,1]
    band = 1.96/np.sqrt(len(r))
    return name, v.mean(), r.std()*100, corr, band

